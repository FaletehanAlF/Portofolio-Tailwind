  let currentIndex = 0;
  let isOpen = false;

  function updateModalContent(index) {
    const cert = CERT_DATA[index];
    const dict = translations[currentLang] || translations.en;
    modalImg.classList.add('is-loading');
    const tmp = new Image();
    tmp.onload = () => { modalImg.src = tmp.src; modalImg.alt = dict[cert.titleKey] || ''; modalImg.classList.remove('is-loading'); };
    tmp.onerror = () => { modalImg.src = cert.src; modalImg.classList.remove('is-loading'); };
    tmp.src = cert.src;
    modalTitle.textContent = dict[cert.titleKey] || cert.titleKey;
    modalIssuer.textContent = dict[cert.issuerKey] || cert.issuerKey;
    modalCounter.textContent = `${index + 1} / ${CERT_DATA.length}`;
    btnPrev.disabled = index <= 0;
    btnNext.disabled = index >= CERT_DATA.length - 1;
  }

