/* =========================================================
   APPLY LANGUAGE
========================================================= */
let currentLang = localStorage.getItem('lang') || 'en';

function refreshNavbarLayout() {
  const active = document.querySelector('.nav-link.active');
  const indicator = document.querySelector('.nav-indicator');
  if (!active || !indicator) return;
  indicator.style.width = active.offsetWidth + 'px';
  indicator.style.left = active.offsetLeft + 'px';
}

function applyLanguage(lang) {
  const dict = translations[lang];
  if (!dict) return;
  currentLang = lang;
  localStorage.setItem('lang', lang);

  // Text elements
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  // Placeholder elements
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });

  // Mark active lang button (semua: desktop + mobile)
  document.querySelectorAll('.lang-option').forEach((btn) => {
    btn.classList.toggle('is-active', btn.getAttribute('data-lang') === lang);
  });

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Bahasa mengubah panjang text => ukuran nav-link berubah
  // Refresh indicator & geometry agar tidak membuat layout terlihat acak
  requestAnimationFrame(() => refreshNavbarLayout());
}


